// Regenerates src/lib/barcode/pdf417Table.ts: the PDF417 codeword bar patterns
// (ISO/IEC 15438 Annex, clusters 0, 3 and 6), read back from symbols rendered by bwip-js.
// Usage: node scripts/gen-pdf417-table.mjs

import fs from 'node:fs';
import { createRequire } from 'node:module';

const bwip = createRequire(import.meta.url)('bwip-js');

const START = 17;
const INDICATOR = 17;
const PER_SYMBOL = 29; // 1 column: 1 length descriptor + 29 × 3 data rows + 2 EC rows = 90 rows.
const tables = [new Array(929), new Array(929), new Array(929)];

for (let first = 0; first < 929; first += PER_SYMBOL) {
  const values = [];
  for (let v = first; v < Math.min(929, first + PER_SYMBOL); v++) values.push(v, v, v);
  const text = values.map((v) => `^${String(v).padStart(3, '0')}`).join('');
  const sym = bwip.raw({ bcid: 'pdf417', text, raw: true, columns: 1, eclevel: 0 })[0];
  // `pixy` is the scaled height; `pixs` holds one pixel row per symbol row.
  const rowHeight = sym.pixs.length / sym.pixx / (1 + values.length + 2);
  if (!Number.isInteger(rowHeight)) throw new Error(`unexpected row count at ${first}`);
  values.forEach((v, i) => {
    const row = i + 1; // row 0 holds the symbol length descriptor
    const y = row * rowHeight;
    const bits = sym.pixs.slice(y * sym.pixx + START + INDICATOR, y * sym.pixx + START + INDICATOR + 17);
    const pattern = parseInt(bits.join(''), 2);
    const cluster = row % 3;
    if (tables[cluster][v] !== undefined && tables[cluster][v] !== pattern) throw new Error(`conflict ${cluster}/${v}`);
    tables[cluster][v] = pattern;
  });
}

for (const [c, t] of tables.entries()) {
  if (t.some((p) => p === undefined)) throw new Error(`cluster ${c * 3} incomplete`);
  if (new Set(t).size !== 929) throw new Error(`cluster ${c * 3} has duplicate patterns`);
  // Every pattern starts with a bar, ends with a space and has 4 bars in 17 modules.
  for (const p of t) {
    const s = p.toString(2).padStart(17, '0');
    if (s[0] !== '1' || s[16] !== '0' || s.match(/1+/g).length !== 4) throw new Error(`bad pattern ${s}`);
  }
}

const rows = (t) => {
  const out = [];
  for (let i = 0; i < t.length; i += 16) out.push(`    ${t.slice(i, i + 16).join(', ')},`);
  return out.join('\n');
};
const ts = `// Generated by scripts/gen-pdf417-table.mjs from symbols rendered by bwip-js (MIT).
// PDF417 codeword bar patterns (ISO/IEC 15438), 17 modules each, most significant bit first
// (1 = bar). Do not edit by hand.

/** Index: cluster / 3 (0, 1, 2 for clusters 0, 3, 6), then codeword value 0..928. */
export const PDF417_PATTERNS: readonly (readonly number[])[] = [
${tables.map((t) => `  [\n${rows(t)}\n  ],`).join('\n')}
];
`;
fs.writeFileSync('src/lib/barcode/pdf417Table.ts', ts);
console.log('wrote src/lib/barcode/pdf417Table.ts');
